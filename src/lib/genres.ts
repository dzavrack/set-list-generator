export function getGenre(key: GenreKey): GenreConfig {
  return GENRES[key] ?? GENRES.jazz;
}

/** All genres in display order. */
export const genreList: GenreConfig[] = GENRE_ORDER.map((k) => GENRES[k]);

/** Compiled style-word regexes for parsing gig descriptions (cached per genre). */
const compiled = new Map<GenreKey, [RegExp, string][]>();
export function styleWordRegexes(key: GenreKey): [RegExp, string][] {
  let r = compiled.get(key);
  if (!r) {
    r = getGenre(key).words.map(([src, code]) => [new RegExp(src, "i"), code] as [RegExp, string]);
    compiled.set(key, r);
  }
  return r;
}
